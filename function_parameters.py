def introduce(name, age, subject):
    print(f"My name is {name}, I am {age} years old, and my favourite subject is {subject}.")


introduce("Alex", 16, "Computer Science")
introduce("Jordan", 17, "Physics")


def calculate_area(width, height):
    area = width * height
    print(f"The area is {area}.")


calculate_area(5, 4)
calculate_area(10, 3)
calculate_area(7, 6)